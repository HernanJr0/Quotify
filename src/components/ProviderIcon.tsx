import type { ProviderKind } from "../types/provider";

interface ProviderIconProps {
  provider: ProviderKind;
}

/**
 * Small, local copies of the providers' marks. Keeping them inline avoids a
 * network request while Quotify is running and lets the mark inherit the
 * accent color used by its card where the original permits it.
 */
export function ProviderIcon({ provider }: ProviderIconProps) {
  switch (provider) {
    case "claude":
      return <ClaudeIcon />;
    case "codex":
      return <CodexIcon />;
    case "gemini":
      return <GeminiIcon />;
    case "grok":
      return <GrokIcon />;
  }
}

